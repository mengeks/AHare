  function(suffix) {
    are <- all_scenarios[[paste0("are_", suffix)]]
    ere <- all_scenarios[[paste0("ere_", suffix)]]
    keep <- is.finite(are) & is.finite(ere) & (are - 1) * (ere - 1) < 0
    c(abs(are[keep] - 1), abs(ere[keep] - 1))
  }))
