get_row <- function(dat, ...) {
  keep <- rep(TRUE, nrow(dat))
  filters <- list(...)
  for (nm in names(filters)) keep <- keep & dat[[nm]] == filters[[nm]]
  dat[keep, , drop = FALSE][1, ]
}
